print("for loop")
sum = 0
for i in range(5):
    num = int(input("enter any numbers : "))
    sum = sum+num
print(sum)


print("while loop")

i = 0
sum = 0
while i < 5:
    num = int(input("enter any numbers : "))
    sum = sum+num

    i = i + 1

print(sum)



